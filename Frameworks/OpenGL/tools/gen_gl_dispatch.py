# Generate the OpenGL entry points exported by OpenGL.framework.
#
# Every GL function of OpenGL 1.0 through 4.1 (the highest version macOS
# offers) becomes an exported symbol that forwards the call to the
# renderer driver of the calling thread's current CGL context. Without a
# context, or when the driver lacks the function, the call does nothing
# and returns 0/NULL.
#
# Prototypes are read from the vendored headers (both MIT licensed):
#   glmesa.h  Mesa's GL/gl.h, for OpenGL 1.0 - 1.3
#   glext.h   Khronos, for OpenGL 1.4 - 4.1
#
# Usage: gen_gl_dispatch.py <include dir> <output dir>

import re
import sys
from pathlib import Path

DECL = re.compile(r'GLAPI\s+(?P<ret>.+?)\s*\b(?:GLAPIENTRY|APIENTRY)\s+'
                  r'(?P<name>gl\w+)\s*\((?P<args>[^)]*)\)\s*;')
VERSION_BLOCK = re.compile(r'^#ifndef\s+(GL_VERSION_(\d)_(\d))\b')
FIRST_EXTENSION = '#ifndef GL_ARB_multitexture'
PARAM_NAME = re.compile(r'(\w+)\s*(\[[^\]]*\])?\s*$')

MAX_VERSION = (4, 1)


def statements(lines):
    """Yield (line, joined statement) pairs, joining GLAPI lines up to ';'."""
    buf = None
    for line in lines:
        if buf is None:
            if line.lstrip().startswith('GLAPI'):
                buf = line.strip()
            else:
                yield line, None
                continue
        else:
            buf += ' ' + line.strip()
        if buf.endswith(';'):
            yield None, buf
            buf = None


def parse_decl(stmt):
    m = DECL.match(stmt)
    if not m:
        raise SystemExit('cannot parse declaration: ' + stmt)
    args = m.group('args').strip()
    params = []
    if args and args != 'void':
        for p in args.split(','):
            p = ' '.join(p.split())
            pm = PARAM_NAME.search(p)
            if not pm:
                raise SystemExit('cannot parse parameter %r in %s' % (p, stmt))
            params.append((p, pm.group(1)))
    return m.group('name'), ' '.join(m.group('ret').split()), params


def mesa_functions(path):
    """OpenGL 1.0 - 1.3 from Mesa's gl.h (everything before its extensions)."""
    funcs = []
    for line, stmt in statements(path.read_text().splitlines()):
        if line is not None and line.startswith(FIRST_EXTENSION):
            break
        if stmt is not None:
            funcs.append(parse_decl(stmt))
    return funcs


def glext_functions(path):
    """OpenGL 1.4 - MAX_VERSION from Khronos glext.h version blocks."""
    funcs, version = [], None
    for line, stmt in statements(path.read_text().splitlines()):
        if line is not None:
            m = VERSION_BLOCK.match(line)
            if m:
                version = (int(m.group(2)), int(m.group(3)))
            elif line.startswith('#ifndef GL_'):
                version = None          # an extension block
            continue
        if version is not None and (1, 4) <= version <= MAX_VERSION:
            funcs.append(parse_decl(stmt))
    return funcs


def default_return(ret):
    return '' if ret == 'void' else '0'


def generate(funcs):
    for name, _, params in funcs:
        if any(n == 'cgl_fn_' for _, n in params):
            raise SystemExit('parameter name clash in ' + name)
    header = ['/* Generated by tools/gen_gl_dispatch.py. Do not edit. */',
              '', '#ifndef _GL_DISPATCH_GEN_H_', '#define _GL_DISPATCH_GEN_H_',
              '', 'enum {']
    header += ['    CGL_GL_%s,' % name for name, _, _ in funcs]
    header += ['    CGL_GL_COUNT', '};', '',
               'extern const char *const cgl_gl_names[CGL_GL_COUNT];', '',
               '#endif /* _GL_DISPATCH_GEN_H_ */', '']

    body = ['/* Generated by tools/gen_gl_dispatch.py. Do not edit. */', '',
            '#include <OpenGL/gl.h>', '', '#include "CGLInternal.h"',
            '#include "GLDispatch.gen.h"', '',
            'const char *const cgl_gl_names[CGL_GL_COUNT] = {']
    body += ['    "%s",' % name for name, _, _ in funcs]
    body += ['};', '']
    for name, ret, params in funcs:
        decl = ', '.join(p for p, _ in params) or 'void'
        types = ', '.join(re.sub(r'\s*\b%s\b\s*(\[[^\]]*\])?\s*$' % n,
                                 lambda m: (' *' if m.group(1) else ''), p)
                          for p, n in params) or 'void'
        call = ', '.join(n for _, n in params)
        fptr = '(%s (GLAPIENTRY *)(%s))' % (ret, types)
        body.append('GLAPI %s GLAPIENTRY %s(%s)' % (ret, name, decl))
        body.append('{')
        body.append('    CGLGLProc cgl_fn_ = cgl_gl_proc(CGL_GL_%s);' % name)
        body.append('')
        if ret == 'void':
            body.append('    if (cgl_fn_ != NULL)')
            body.append('        (%scgl_fn_)(%s);' % (fptr, call))
        else:
            body.append('    if (cgl_fn_ == NULL)')
            body.append('        return %s;' % default_return(ret))
            body.append('    return (%scgl_fn_)(%s);' % (fptr, call))
        body.append('}')
        body.append('')
    return '\n'.join(header), '\n'.join(body)


def main(argv):
    if len(argv) != 3:
        raise SystemExit('usage: gen_gl_dispatch.py <include dir> <output dir>')
    inc, out = Path(argv[1]), Path(argv[2])

    funcs, seen = [], set()
    for f in mesa_functions(inc / 'glmesa.h') + glext_functions(inc / 'glext.h'):
        if f[0] not in seen:
            seen.add(f[0])
            funcs.append(f)

    header, body = generate(funcs)
    (out / 'GLDispatch.gen.h').write_text(header)
    (out / 'GLDispatch.gen.c').write_text(body)
    print('%d OpenGL entry points' % len(funcs))


if __name__ == '__main__':
    main(sys.argv)
