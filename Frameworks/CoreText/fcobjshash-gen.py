# Generates fontconfig's src/fcobjshash.h without GNU gperf.
#
# fontconfig only needs FcObjectTypeLookup(str, len), returning a
# struct FcObjectTypeInfo { int name; int id; } for a fixed set of about
# 50 property names, with 'name' an offset into FcObjectTypeNamePool.
# We emit a sorted table and look names up with a binary search.
#
# Usage (drop-in for the build's $(GPERF) call; gperf options are ignored):
#   fcobjshash-gen.py [options] fcobjshash.gperf > fcobjshash.h

import sys


def parse(path):
    """Return (verbatim C code, declarations, [(name, id_expr), ...])."""
    with open(path) as f:
        lines = f.read().splitlines()

    code, decls, keys = [], [], []
    section = "decls"
    in_code = False
    for line in lines:
        s = line.strip()
        if section == "decls":
            if s == "%{":
                in_code = True
            elif s == "%}":
                in_code = False
            elif in_code:
                code.append(line)
            elif s == "%%":
                section = "keys"
            elif s.startswith("%") or not s:
                continue
            else:
                decls.append(line)
        else:
            if s == "%%":
                break
            if not s or s.startswith("#"):
                continue
            # Lines look like:  "family",FC_FAMILY_OBJECT
            if not s.startswith('"'):
                raise SystemExit("fcobjshash-gen: bad key line: %r" % line)
            end = s.index('"', 1)
            name = s[1:end]
            rest = s[end + 1:].lstrip(" \t,").strip()
            keys.append((name, rest))
    return code, decls, keys


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(argv):
    inputs = [a for a in argv[1:] if not a.startswith("-")]
    # gperf's "-m 100" takes a separate value; drop bare numbers.
    inputs = [a for a in inputs if not a.isdigit()]
    if len(inputs) != 1:
        raise SystemExit("usage: fcobjshash-gen.py [options] input.gperf")

    code, decls, keys = parse(inputs[0])
    keys.sort(key=lambda k: k[0].encode())
    names = [k[0] for k in keys]
    if len(set(names)) != len(names):
        raise SystemExit("fcobjshash-gen: duplicate keys")

    out = []
    w = out.append
    w("/* Generated by fcobjshash-gen.py. Do not edit. */")
    w("")
    w("\n".join(code))
    w("#include <string.h>")
    w("")
    w("\n".join(decls))
    w("")

    # String pool: one char array per name, so offsets are compile-time.
    w("struct FcObjectTypeNamePool_t {")
    for i, n in enumerate(names):
        w("    char str%d[sizeof(%s)];" % (i, c_string(n)))
    w("};")
    w("static const struct FcObjectTypeNamePool_t FcObjectTypeNamePool_contents = {")
    for n in names:
        w("    %s," % c_string(n))
    w("};")
    w("#define FcObjectTypeNamePool ((const char *) &FcObjectTypeNamePool_contents)")
    w("")

    w("static const struct FcObjectTypeInfo FcObjectTypeTable[] = {")
    for i, (n, ident) in enumerate(keys):
        w("    { (int)(size_t)&((struct FcObjectTypeNamePool_t *)0)->str%d, %s }," % (i, ident))
    w("};")
    w("")

    w("static unsigned int")
    w("FcObjectTypeHash (register const char *str, register FC_GPERF_SIZE_T len)")
    w("{")
    w("    /* FNV-1a; kept for API compatibility, lookups don't need it. */")
    w("    unsigned int h = 2166136261u;")
    w("    while (len--)")
    w("        h = (h ^ (unsigned char) *str++) * 16777619u;")
    w("    return h;")
    w("}")
    w("")

    w("static const struct FcObjectTypeInfo *")
    w("FcObjectTypeLookup (register const char *str, register FC_GPERF_SIZE_T len)")
    w("{")
    w("    size_t lo = 0, hi = sizeof (FcObjectTypeTable) / sizeof (FcObjectTypeTable[0]);")
    w("")
    w("    (void) FcObjectTypeHash;")
    w("    while (lo < hi) {")
    w("        size_t mid = lo + (hi - lo) / 2;")
    w("        const char *key = FcObjectTypeNamePool + FcObjectTypeTable[mid].name;")
    w("        size_t klen = strlen (key);")
    w("        size_t n = len < klen ? len : klen;")
    w("        int c = memcmp (str, key, n);")
    w("")
    w("        if (c == 0)")
    w("            c = (len > klen) - (len < klen);")
    w("        if (c == 0)")
    w("            return &FcObjectTypeTable[mid];")
    w("        if (c < 0)")
    w("            hi = mid;")
    w("        else")
    w("            lo = mid + 1;")
    w("    }")
    w("    return NULL;")
    w("}")

    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv)
