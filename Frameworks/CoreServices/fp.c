/*
 * The floating-point functions CoreServices exports on the reference
 * platform (its fp.h), for binaries that bound them to CoreServices rather
 * than to libSystem: VLC's interface imports exp2 from here. Each is the
 * C library's.
 */

#include <math.h>

/* Through a pointer the compiler cannot see through: it would turn
 * pow(2.0, x) into a call to exp2, this function. */
static double (*volatile c_pow)(double, double) = pow;

double exp2(double x) {
	return c_pow(2.0, x);
}
