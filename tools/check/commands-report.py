"""How far Minkar's command-line tools have come, as Markdown.

  commands-report.py --sysroot S [--repo R] [--since COMMIT] > Docs/Commands.md

Counts the commands in the sysroot's /bin, /sbin, /usr/bin and /usr/sbin;
the command directories in the repository's BSD/ tree now and at COMMIT
(default 60aa4ff4b1, where Minkar left ravynOS); and which commands of
macos-commands.txt (next to this script) the sysroot has, by kind.
"""

import argparse
import os
import subprocess
import sys

DIRS = ['bin', 'sbin', 'usr/bin', 'usr/sbin']
TREES = ['BSD/bin', 'BSD/sbin', 'BSD/usr.bin', 'BSD/usr.sbin']
KINDS = [
    ('bsd', 'BSD and other portable tools',
     'Ported from FreeBSD main (or their own upstream), as the ones before.'),
    ('apple', "macOS's own tools",
     'Written for Minkar; many need the graphical system or frameworks of '
     'later phases.'),
    ('darwin', "Darwin's own components",
     "Kept from Apple's open source (launchd, configd, syslogd...)."),
    ('fs', 'File system tools',
     'Need the file system (APFS, exFAT, FAT, NFS, SMB) in the kernel first.'),
    ('licence', 'Licence to approve',
     'Their licence (GPL, Vim, CDDL...) needs the project\'s approval first.'),
    ('builtin', 'Shell builtins as files',
     'macOS has /usr/bin/cd and the like: small scripts that run the '
     'builtin.'),
]


def sysroot_commands(sysroot):
    names = {}
    for d in DIRS:
        path = os.path.join(sysroot, d)
        try:
            entries = os.listdir(path)
        except OSError:
            entries = []
        names[d] = sorted(e for e in entries
                          if os.path.isfile(os.path.join(path, e))
                          or os.path.islink(os.path.join(path, e)))
    return names


def tree_dirs(repo, commit, tree):
    ref = '%s:%s' % (commit, tree)
    out = subprocess.run(['git', '-C', repo, 'ls-tree', '-d', '--name-only',
                          ref], capture_output=True, text=True)
    return len(out.stdout.split()) if out.returncode == 0 else 0


def reference(path):
    rows = []
    with open(path) as f:
        for line in f:
            line = line.split('#')[0].split()
            if len(line) == 3:
                rows.append(tuple(line))
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--sysroot', required=True)
    ap.add_argument('--repo', default='.')
    ap.add_argument('--since', default='60aa4ff4b1')
    a = ap.parse_args()

    here = os.path.dirname(os.path.abspath(__file__))
    ref = reference(os.path.join(here, 'macos-commands.txt'))
    have = sysroot_commands(a.sysroot)
    present = set()
    for d in DIRS:
        present.update(have[d])

    out = sys.stdout.write
    out('# Command-line tools\n\n')
    out('How many of the commands a macOS user types Minkar has, and how '
        'many it still lacks. This page is generated by '
        '`tools/check/commands-report.py` from a built sysroot; the '
        'reference list is `tools/check/macos-commands.txt` (%d commands '
        'of macOS\'s /bin, /sbin, /usr/bin and /usr/sbin, without Xcode\'s '
        'developer tools or Perl and Python scripts).\n\n' % len(ref))
    out('Each command comes from FreeBSD main where FreeBSD has it, and '
        'behaves as on macOS where the two differ; each has its manual page '
        'and its tests.\n\n')

    out('## In the system image\n\n')
    out('| Directory | Commands |\n|---|---:|\n')
    total = 0
    for d in DIRS:
        out('| `/%s` | %d |\n' % (d, len(have[d])))
        total += len(have[d])
    out('| **Total** | **%d** |\n\n' % total)

    out('## In the source tree\n\n')
    out('Command directories under `BSD/`, at commit `%s` (where Minkar '
        'started from ravynOS) and now:\n\n' % a.since)
    out('| Directory | Then | Now |\n|---|---:|---:|\n')
    then_t = now_t = 0
    for t in TREES:
        then = tree_dirs(a.repo, a.since, t)
        now = tree_dirs(a.repo, 'HEAD', t)
        then_t += then
        now_t += now
        out('| `%s` | %d | %d |\n' % (t, then, now))
    out('| **Total** | **%d** | **%d** |\n\n' % (then_t, now_t))

    have_n = sum(1 for _, n, _ in ref if n in present)
    out('## Against macOS\n\n')
    out('%d of the %d reference commands are in the image; %d are '
        'missing.\n\n' % (have_n, len(ref), len(ref) - have_n))
    out('| Kind | In the image | Missing | What it takes |\n'
        '|---|---:|---:|---|\n')
    for kind, title, note in KINDS:
        rows = [n for _, n, k in ref if k == kind]
        h = sum(1 for n in rows if n in present)
        out('| %s | %d | %d | %s |\n' % (title, h, len(rows) - h, note))
    out('\n### Missing\n\n')
    for kind, title, _ in KINDS:
        miss = sorted(n for _, n, k in ref if k == kind and n not in present)
        if miss:
            out('- **%s** (%d): %s\n' % (title, len(miss),
                                        ', '.join('`%s`' % n for n in miss)))
    out('\n')


if __name__ == '__main__':
    main()
