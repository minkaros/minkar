def sysroot_commands(sysroot):
    names = {}
    for d in DIRS:
        path = os.path.join(sysroot, d)
        try:
            entries = os.listdir(path)
        except OSError:
            entries = []
        names[d] = sorted(e for e in entries
                          if os.path.isfile(os.path.join(path, e))
                          or os.path.islink(os.path.join(path, e)))
    return names


def tree_dirs(repo, commit, tree):
    ref = '%s:%s' % (commit, tree)
    out = subprocess.run(['git', '-C', repo, 'ls-tree', '-d', '--name-only',
                          ref], capture_output=True, text=True)
    return len(out.stdout.split()) if out.returncode == 0 else 0


def reference(path):
    rows = []
    with open(path) as f:
        for line in f:
            line = line.split('#')[0].split()
            if len(line) == 3:
                rows.append(tuple(line))
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--sysroot', required=True)
    ap.add_argument('--repo', default='.')
    ap.add_argument('--since', default='60aa4ff4b1')
    ap.add_argument('--lang', choices=['en', 'es'], default='en')
    a = ap.parse_args()
    t = TEXT[a.lang]
    kinds = [(k, *(KINDS_ES[k] if a.lang == 'es' else (title, note))) for k, title, note in KINDS]

    here = os.path.dirname(os.path.abspath(__file__))
    ref = reference(os.path.join(here, 'reference-commands.txt'))
    have = sysroot_commands(a.sysroot)
    present = set()
    for d in DIRS:
        present.update(have[d])

    out = sys.stdout.write
    out(t['title'])
    out(t['intro'] % len(ref))
    out(t['other'])
    out(t['origin'])

    out(t['image'])
    out(t['image_head'])
    total = 0
    for d in DIRS:
        out('| `/%s` | %d |\n' % (d, len(have[d])))
        total += len(have[d])
    out('| **%s** | **%d** |\n\n' % (t['total'], total))

    out(t['tree'])
    out(t['tree_intro'] % a.since)
    out(t['tree_head'])
    then_t = now_t = 0
    for tree in TREES:
        then = tree_dirs(a.repo, a.since, tree)
        now = tree_dirs(a.repo, 'HEAD', tree)
        then_t += then
        now_t += now
        out('| `%s` | %d | %d |\n' % (tree, then, now))
    out('| **%s** | **%d** | **%d** |\n\n' % (t['total'], then_t, now_t))

    have_n = sum(1 for _, n, _ in ref if n in present)
    out(t['ref'])
    out(t['ref_intro'] % (have_n, len(ref), len(ref) - have_n))
    out(t['ref_head'])
    for kind, title, note in kinds:
        rows = [n for _, n, k in ref if k == kind]
        h = sum(1 for n in rows if n in present)
        out('| %s | %d | %d | %s |\n' % (title, h, len(rows) - h, note))
    out(t['missing'])
    for kind, title, _ in kinds:
        miss = sorted(n for _, n, k in ref if k == kind and n not in present)
        if miss:
            out('- **%s** (%d): %s\n' % (title, len(miss),
                                        ', '.join('`%s`' % n for n in miss)))
    out('\n')


if __name__ == '__main__':
    main()
