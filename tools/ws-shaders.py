"""
ws-shaders.py: the window server's Vulkan shaders (GPU track G4) as
SPIR-V, from PrivateFrameworks/SkyLight/Server/shaders/*.comp, compiled by
glslangValidator for Vulkan 1.2 and written as arrays to
PrivateFrameworks/SkyLight/Server/WSVulkanShaders.h. The window server is
built before the build host's glslang (BSD/lib/mesa), so the header is kept
in the tree; run this after changing a shader.

    ws-shaders.py [--glslang PATH] [--check]

glslangValidator is --glslang, else $GLSLANG, else the one on PATH.

--check compares the header with what the shaders compile to (exit
status 1 if it differs).
"""

import argparse
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SERVER = os.path.join(HERE, '..', 'PrivateFrameworks', 'SkyLight', 'Server')
SHADERS = os.path.join(SERVER, 'shaders')
OUT = os.path.join(SERVER, 'WSVulkanShaders.h')
# The build's own is in BSD/lib/mesa's object directory, host-tools/bin.
DEFAULT_GLSLANG = 'glslangValidator'


def compile_shader(glslang, path):
    with tempfile.TemporaryDirectory() as tmp:
        spv = os.path.join(tmp, 'out.spv')
        r = subprocess.run([glslang, '-V', '--target-env', 'vulkan1.2', '-o', spv, path],
                           capture_output=True, text=True)
        if r.returncode != 0:
            sys.exit('ws-shaders: %s: %s' % (path, r.stdout + r.stderr))
        data = open(spv, 'rb').read()
    return [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]


def header(glslang):
    lines = ['/*', ' * SPDX-License-Identifier: BSD-2-Clause', ' *',
             ' * Copyright (c) 2026 The Minkar contributors', ' * Part of Minkar.', ' *',
             ' * Generated by tools/ws-shaders.py from shaders/; do not edit.', ' */', '',
             '#include <stdint.h>', '']
    for name in sorted(os.listdir(SHADERS)):
        if not name.endswith('.comp'):
            continue
        words = compile_shader(glslang, os.path.join(SHADERS, name))
        var = 'kWS' + ''.join(p.capitalize() for p in name[:-5].split('_')) + 'Shader'
        lines.append('static const uint32_t %s[] = {' % var)
        for i in range(0, len(words), 8):
            lines.append('\t' + ', '.join('0x%08x' % w for w in words[i:i + 8]) + ',')
        lines.append('};')
        lines.append('')
    return '\n'.join(lines)


def main():
    p = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    p.add_argument('--glslang', default=os.environ.get('GLSLANG', DEFAULT_GLSLANG))
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    text = header(args.glslang)
    if args.check:
        same = os.path.exists(OUT) and open(OUT).read() == text
        print('ws-shaders: %s' % ('matches the shaders' if same else 'differs from the shaders'))
        return 0 if same else 1
    open(OUT, 'w').write(text)
    print('ws-shaders: wrote %s' % os.path.relpath(OUT))
    return 0


if __name__ == '__main__':
    sys.exit(main())
