"""
smu11-layout.py: the sizes and offsets of AMD's SMU 11.0.7 tables (Navi
21 to 23) that MinkarDRM uses to hand the SMU its power play table, from
drm-kmod's amdgpu headers (MIT) at the version dist/FILES pins, compiled
with the host's C compiler: PPTable_t's size, where it lies in the
VBIOS's powerplayinfo table, the board's part of it that the
smc_dpm_info table gives, and the two data tables' indices. Written,
with the source's MIT notice, to amdgpu/amd_smu11_layout.h.

    smu11-layout.py [--source DIR] [--check]
"""

import argparse
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
DRM = os.path.join(HERE, '..', '..', 'Kernel', 'Extensions', 'MinkarDRM')
OUT = os.path.join(DRM, 'amdgpu', 'amd_smu11_layout.h')

PROGRAM = r'''
#include <stdint.h>
#include <stddef.h>
#include <stdio.h>
#include "atomfirmware.h"
#include "smu11_driver_if_sienna_cichlid.h"
#include "smu_v11_0_7_pptable.h"
#define END(t, m) (offsetof(t, m) + sizeof(((t *)0)->m))
int main(void) {
	printf("AMD_SMU11_PPTABLE_BYTES %zu\n", sizeof(PPTable_t));
	printf("AMD_SMU11_PPTABLE_IN_POWERPLAY %zu\n", offsetof(struct smu_11_0_7_powerplay_table, smc_pptable));
	printf("AMD_SMU11_BOARD_OFFSET %zu\n", offsetof(PPTable_t, I2cControllers));
	printf("AMD_SMU11_BOARD_BYTES %zu\n", END(PPTable_t, BoardReserved) - offsetof(PPTable_t, I2cControllers));
	printf("AMD_SMU11_DPM_INFO_BOARD_OFFSET %zu\n", offsetof(struct atom_smc_dpm_info_v4_9, I2cControllers));
	printf("AMD_ATOM_DATA_POWERPLAYINFO %zu\n", offsetof(struct atom_master_list_of_data_tables_v2_1, powerplayinfo) / 2);
	printf("AMD_ATOM_DATA_SMC_DPM_INFO %zu\n", offsetof(struct atom_master_list_of_data_tables_v2_1, smc_dpm_info) / 2);
	printf("AMD_SMU11_DRIVER_IF_VERSION %u\n", SMU11_DRIVER_IF_VERSION);
	return 0;
}
'''


def run(source):
    amd = os.path.join(source, 'drivers', 'gpu', 'drm', 'amd')
    notice = open(os.path.join(amd, 'pm', 'swsmu', 'inc', 'smu_v11_0_7_pptable.h')).read()
    notice = notice[:notice.index('*/') + 2]
    with tempfile.TemporaryDirectory() as d:
        c = os.path.join(d, 'layout.c')
        open(c, 'w').write(PROGRAM)
        exe = os.path.join(d, 'layout')
        subprocess.run(['cc', '-D__counted_by(x)=', '-I' + os.path.join(amd, 'include'),
                        '-I' + os.path.join(amd, 'pm', 'swsmu', 'inc'),
                        '-I' + os.path.join(amd, 'pm', 'swsmu', 'inc', 'pmfw_if'), c, '-o', exe],
                       check=True)
        lines = subprocess.run([exe], check=True, capture_output=True, text=True).stdout.split('\n')
    return [l.split() for l in lines if l], notice


def header(values, notice, version):
    out = [notice, '',
           '/*',
           ' * SMU 11.0.7 table layout (Navi 21 to 23): generated by',
           ' * tools/drm-import/smu11-layout.py from drm-kmod %s' % version,
           ' * (smu11_driver_if_sienna_cichlid.h, smu_v11_0_7_pptable.h and',
           ' * atomfirmware.h, compiled), under the notice above. Do not edit: run',
           ' * the tool again.',
           ' */', '',
           '#ifndef _MINKAR_AMD_SMU11_LAYOUT_H',
           '#define _MINKAR_AMD_SMU11_LAYOUT_H', '']
    for name, value in values:
        out.append('#define %s\t%s' % (name, value))
    out += ['', '#endif', '']
    return '\n'.join(out)


def main(argv):
    p = argparse.ArgumentParser(description='Writes amdgpu/amd_smu11_layout.h.')
    p.add_argument('--source', default=os.environ.get('MINKAR_DRM_SOURCE'))
    p.add_argument('--check', action='store_true')
    args = p.parse_args(argv)
    if args.source is None:
        sys.exit('smu11-layout: no source (--source or $MINKAR_DRM_SOURCE)')
    version = None
    for line in open(os.path.join(DRM, 'dist', 'FILES')):
        if line.startswith('version '):
            version = line.split()[1]
    values, notice = run(args.source)
    text = header(values, notice, version)
    if args.check:
        same = os.path.exists(OUT) and open(OUT).read() == text
        print('smu11-layout: %s' % ('matches the source' if same else 'differs from the source'))
        return 0 if same else 1
    open(OUT, 'w').write(text)
    print('smu11-layout: wrote %s' % os.path.relpath(OUT))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
