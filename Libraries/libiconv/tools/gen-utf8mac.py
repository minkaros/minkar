# Writes utf8mac_data.h, the tables of the UTF-8-MAC encoding (utf8mac.c),
# from the Unicode Character Database files in Libraries/ICU:
#
#   gen-utf8mac.py UnicodeData.txt DerivedNormalizationProps.txt > utf8mac_data.h
#
# Tables: the canonical decompositions (one level), the non-zero canonical
# combining classes, and the canonical compositions (pairs whose composite
# is not excluded from composition). Characters in the ranges HFS Plus
# leaves composed (U+2000-U+2FFF, U+F900-U+FAFF, U+2F800-U+2FAFF) are
# neither decomposed nor composed.

import sys


def hfs_kept(cp):
    return (0x2000 <= cp <= 0x2FFF or 0xF900 <= cp <= 0xFAFF
            or 0x2F800 <= cp <= 0x2FAFF)


def main():
    ucd, dnp = sys.argv[1], sys.argv[2]
    decomp, ccc = {}, {}
    with open(ucd, encoding='utf-8') as f:
        for line in f:
            fields = line.rstrip('\n').split(';')
            cp = int(fields[0], 16)
            if int(fields[3]):
                ccc[cp] = int(fields[3])
            d = fields[5]
            if d and not d.startswith('<'):
                decomp[cp] = [int(x, 16) for x in d.split()]
    excluded = set()
    with open(dnp, encoding='utf-8') as f:
        for line in f:
            line = line.split('#')[0].strip()
            if not line:
                continue
            rng, prop = [x.strip() for x in line.split(';')[:2]]
            if prop != 'Full_Composition_Exclusion':
                continue
            lo, _, hi = rng.partition('..')
            for cp in range(int(lo, 16), int(hi or lo, 16) + 1):
                excluded.add(cp)

    decomp = {cp: d for cp, d in decomp.items() if not hfs_kept(cp)}
    comps = sorted((d[0], d[1], cp) for cp, d in decomp.items()
                   if len(d) == 2 and cp not in excluded)
    seconds = sorted({c[1] for c in comps})

    out = sys.stdout
    out.write('/* Generated by tools/gen-utf8mac.py from the Unicode Character\n'
              ' * Database (Libraries/ICU/source/data/unidata). Do not edit. */\n\n')
    out.write('static const struct u8m_decomp u8m_decomp[] = {\n')
    for cp in sorted(decomp):
        d = decomp[cp] + [0]
        out.write('\t{ 0x%05X, 0x%05X, 0x%05X },\n' % (cp, d[0], d[1]))
    out.write('};\n\nstatic const struct u8m_ccc u8m_ccc[] = {\n')
    for cp in sorted(ccc):
        out.write('\t{ 0x%05X, %d },\n' % (cp, ccc[cp]))
    out.write('};\n\nstatic const struct u8m_comp u8m_comp[] = {\n')
    for a, b, c in comps:
        out.write('\t{ 0x%05X, 0x%05X, 0x%05X },\n' % (a, b, c))
    out.write('};\n\nstatic const uint32_t u8m_second[] = {\n')
    for i in range(0, len(seconds), 6):
        out.write('\t' + ', '.join('0x%05X' % s for s in seconds[i:i + 6]) + ',\n')
    out.write('};\n')


if __name__ == '__main__':
    main()
