"""Writes digest_tables.h: the MD5 and SHA-2 constants, computed from
their definitions (RFC 1321 section 3.4; FIPS 180-4 sections 4.2 and 5.3)
rather than typed in. Run: python3 gen_tables.py > digest_tables.h"""

import math
from decimal import Decimal, getcontext

getcontext().prec = 100


def primes(n):
    found, i = [], 2
    while len(found) < n:
        if all(i % p for p in found):
            found.append(i)
        i += 1
    return found


def frac_bits(p, root, bits, skip=0):
    """The fractional part of p**(1/root), as bits bits after skip bits."""
    x = Decimal(p) ** (Decimal(1) / Decimal(root))
    f = int((x - int(x)) * (2 ** (bits + skip)))
    return f & ((1 << bits) - 1)


P = primes(80)
tables = [
    ('uint32_t', 'md5_T', 8, [int(abs(math.sin(i + 1)) * 2 ** 32) & 0xffffffff
                               for i in range(64)]),
    ('uint32_t', 'sha256_K', 8, [frac_bits(p, 3, 32) for p in P[:64]]),
    ('uint32_t', 'sha256_H0', 8, [frac_bits(p, 2, 32) for p in P[:8]]),
    ('uint32_t', 'sha224_H0', 8, [frac_bits(p, 2, 32, 32) for p in P[8:16]]),
    ('uint64_t', 'sha512_K', 16, [frac_bits(p, 3, 64) for p in P[:80]]),
    ('uint64_t', 'sha512_H0', 16, [frac_bits(p, 2, 64) for p in P[:8]]),
    ('uint64_t', 'sha384_H0', 16, [frac_bits(p, 2, 64) for p in P[8:16]]),
]

print('/* Generated by gen_tables.py; do not edit. */\n')
for ctype, name, width, values in tables:
    per = 4 if width == 8 else 2
    suffix = 'U' if width == 8 else 'ULL'
    print('static const %s %s[%d] = {' % (ctype, name, len(values)))
    for i in range(0, len(values), per):
        row = ', '.join('0x%0*x%s' % (width, v, suffix) for v in values[i:i + per])
        print('\t%s,' % row)
    print('};\n')
