"""Writes the constant tables, computed from their definitions rather than
typed in:
  python3 gen_tables.py digest > digest_tables.h   MD5 and SHA-2 (RFC 1321
      section 3.4; FIPS 180-4 sections 4.2 and 5.3)
  python3 gen_tables.py aes > aes_tables.h         AES S-box, its inverse
      and the round constants (FIPS 197 sections 5.1.1 and 5.2)"""

import math
import sys
from decimal import Decimal, getcontext

getcontext().prec = 100


def primes(n):
    found, i = [], 2
    while len(found) < n:
        if all(i % p for p in found):
            found.append(i)
        i += 1
    return found


def frac_bits(p, root, bits, skip=0):
    """The fractional part of p**(1/root), as bits bits after skip bits."""
    x = Decimal(p) ** (Decimal(1) / Decimal(root))
    f = int((x - int(x)) * (2 ** (bits + skip)))
    return f & ((1 << bits) - 1)


def gf_mul(a, b):
    """Multiplication in GF(2^8) modulo x^8 + x^4 + x^3 + x + 1."""
    r = 0
    while b:
        if b & 1:
            r ^= a
        a = ((a << 1) ^ 0x11b) if a & 0x80 else a << 1
        b >>= 1
    return r


def aes_sbox():
    sbox = []
    for x in range(256):
        inv = next((y for y in range(1, 256) if gf_mul(x, y) == 1), 0)
        b = inv
        for shift in (1, 2, 3, 4):
            b ^= ((inv << shift) | (inv >> (8 - shift))) & 0xff
        sbox.append(b ^ 0x63)
    return sbox


def aes_tables():
    sbox = aes_sbox()
    inv = [0] * 256
    for i, v in enumerate(sbox):
        inv[v] = i
    rcon, r = [], 1
    for _ in range(10):
        rcon.append(r)
        r = gf_mul(r, 2)
    return [('uint8_t', 'aes_sbox', 2, sbox), ('uint8_t', 'aes_inv_sbox', 2, inv),
            ('uint8_t', 'aes_rcon', 2, rcon)]


P = primes(80)
tables = [
    ('uint32_t', 'md5_T', 8, [int(abs(math.sin(i + 1)) * 2 ** 32) & 0xffffffff
                               for i in range(64)]),
    ('uint32_t', 'sha256_K', 8, [frac_bits(p, 3, 32) for p in P[:64]]),
    ('uint32_t', 'sha256_H0', 8, [frac_bits(p, 2, 32) for p in P[:8]]),
    ('uint32_t', 'sha224_H0', 8, [frac_bits(p, 2, 32, 32) for p in P[8:16]]),
    ('uint64_t', 'sha512_K', 16, [frac_bits(p, 3, 64) for p in P[:80]]),
    ('uint64_t', 'sha512_H0', 16, [frac_bits(p, 2, 64) for p in P[:8]]),
    ('uint64_t', 'sha384_H0', 16, [frac_bits(p, 2, 64) for p in P[8:16]]),
]

which = sys.argv[1] if len(sys.argv) > 1 else 'digest'
if which == 'aes':
    tables = aes_tables()
print('/* Generated by gen_tables.py %s; do not edit. */\n' % which)
for ctype, name, width, values in tables:
    per = {2: 16, 8: 4, 16: 2}[width]
    suffix = {2: '', 8: 'U', 16: 'ULL'}[width]
    print('static const %s %s[%d] = {' % (ctype, name, len(values)))
    for i in range(0, len(values), per):
        row = ', '.join('0x%0*x%s' % (width, v, suffix) for v in values[i:i + per])
        print('\t%s,' % row)
    print('};\n')
